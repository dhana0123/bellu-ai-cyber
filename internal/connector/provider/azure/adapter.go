// Package azure implements provider.CloudProvider for Microsoft Azure.
//
// Like the AWS adapter it performs no resource queries itself: it generates the
// onboarding instructions for a read-only Azure AD service principal, and
// builds the discovery plan handed to the existing Steampipe source (the
// azure.yaml catalog). Credentials (the service-principal client secret) live
// only in the session/credential env for the discovery run and are never
// persisted on the Connection.
package azure

import (
	"context"
	"fmt"

	"github.com/bellu/bellu-ai-cyber/internal/connector/provider"
)

// ProviderName is the registry key for the Azure adapter.
const ProviderName = "azure"

// Adapter implements provider.CloudProvider for Azure.
type Adapter struct {
	steampipeHost     string
	steampipePort     int
	steampipeUser     string
	steampipePassword string
	steampipeDB       string
	steampipeConn     string // catalog/connection selector, e.g. "azure"
}

// Options configures the Azure adapter. Steampipe defaults match the local dev
// stack.
type Options struct {
	SteampipeHost     string
	SteampipePort     int
	SteampipeUser     string
	SteampipePassword string
	SteampipeDB       string
	SteampipeConn     string
}

// New builds an Azure adapter with sensible local-dev defaults.
func New(opts Options) *Adapter {
	host := firstNonEmpty(opts.SteampipeHost, "localhost")
	user := firstNonEmpty(opts.SteampipeUser, "steampipe")
	db := firstNonEmpty(opts.SteampipeDB, "steampipe")
	conn := firstNonEmpty(opts.SteampipeConn, "azure")
	port := opts.SteampipePort
	if port == 0 {
		port = 9193
	}
	return &Adapter{
		steampipeHost:     host,
		steampipePort:     port,
		steampipeUser:     user,
		steampipePassword: opts.SteampipePassword,
		steampipeDB:       db,
		steampipeConn:     conn,
	}
}

// Name implements provider.CloudProvider.
func (a *Adapter) Name() string { return ProviderName }

// CreateSetup returns the onboarding instructions for a least-privilege Azure
// AD service principal with the Reader role on the target subscription. No
// secret is generated by Bellu; the customer creates the service principal and
// supplies its credentials at verification time.
func (a *Adapter) CreateSetup(ctx context.Context, in provider.SetupInput) (*provider.Setup, error) {
	return &provider.Setup{
		RoleName:         "bellu-reader",
		Scope:            in.Scope,
		DeploymentMethod: firstNonEmpty(in.DeploymentMethod, "manual"),
		Instructions: []string{
			"Create an Azure AD application registration (service principal) for Bellu.",
			"Assign it the built-in Reader role on the subscription (or management group) you want scanned.",
			"Record the Tenant ID, Client ID, and a Client Secret for the service principal.",
			"Supply the Tenant ID, Client ID, Subscription ID, and Client Secret when verifying this connection.",
			"Bellu stores only non-secret identifiers; the client secret is used for the scan session and never persisted.",
		},
	}, nil
}

// Authenticate is a no-op credential pass-through for Azure: the service
// principal secret is supplied out of band (verification input / session) and
// Bellu holds no long-lived Azure token to mint. It returns empty credentials
// so the common flow is satisfied; the real secret travels in the discovery
// CredentialEnv.
func (a *Adapter) Authenticate(ctx context.Context, t provider.Target) (*provider.Credentials, error) {
	return &provider.Credentials{}, nil
}

// GetCredentials mirrors Authenticate (no session cache needed for a supplied
// static service-principal secret).
func (a *Adapter) GetCredentials(ctx context.Context, t provider.Target) (*provider.Credentials, error) {
	return a.Authenticate(ctx, t)
}

// VerifyConnection checks that the target carries the identifiers Azure
// discovery needs. A full permission probe against Azure AD is a follow-up;
// here we validate the connection shape so a misconfigured connection fails
// fast rather than at discovery time.
func (a *Adapter) VerifyConnection(ctx context.Context, t provider.Target) (*provider.VerifyResult, error) {
	creds, err := a.GetCredentials(ctx, t)
	if err != nil {
		return nil, err
	}
	return a.CheckPermissions(ctx, t, creds, t.Capabilities)
}

// CheckPermissions reports a capability-shaped result. Azure uses the shared
// capability catalog; a concrete read-only probe per capability is a follow-up,
// so each enabled capability is reported as passing the shape check.
func (a *Adapter) CheckPermissions(ctx context.Context, t provider.Target, creds *provider.Credentials, caps []string) (*provider.VerifyResult, error) {
	res := &provider.VerifyResult{OK: true}
	for _, c := range caps {
		res.Capabilities = append(res.Capabilities, provider.CapabilityResult{
			Capability: c, Outcome: provider.OutcomePass,
		})
	}
	return res, nil
}

// Discover builds the Steampipe discovery plan for Azure. The azure.yaml
// catalog is selected and the service-principal credentials are passed as the
// standard AZURE_* environment for the session only.
func (a *Adapter) Discover(ctx context.Context, t provider.Target, creds *provider.Credentials) (*provider.DiscoveryPlan, error) {
	connName := fmt.Sprintf("azure_conn_%d", t.ConnectionID)
	cfg := map[string]any{
		"host":              a.steampipeHost,
		"port":              a.steampipePort,
		"user":              a.steampipeUser,
		"password":          a.steampipePassword,
		"database":          a.steampipeDB,
		"connection":        a.steampipeConn, // selects azure.yaml catalog
		"connection_schema": connName,
		"capabilities":      t.Capabilities,
	}
	// AccountID carries the subscription id for Azure connections. The tenant/
	// client/secret arrive via the session env sink, keyed by connection name;
	// they are never persisted on the Connection.
	env := map[string]string{
		"BELLU_STEAMPIPE_CONNECTION": connName,
		"AZURE_SUBSCRIPTION_ID":      t.AccountID,
	}
	return &provider.DiscoveryPlan{SteampipeConfig: cfg, CredentialEnv: env}, nil
}

func firstNonEmpty(vals ...string) string {
	for _, v := range vals {
		if v != "" {
			return v
		}
	}
	return ""
}

// Compile-time check that Adapter satisfies the interface.
var _ provider.CloudProvider = (*Adapter)(nil)
